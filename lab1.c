// Подключаем заголовок со стандартными целочисленными типами фиксированной ширины:
// uint8_t (8 бит без знака), uint32_t (32 бита без знака). Это гарантирует, что размер
// переменных точно соответствует размеру регистров и байтов обмена, независимо от компилятора.
#include <stdint.h>
// Подключаем CMSIS-заголовок конкретного МК STM32F407: в нём описаны структуры периферии
// (I2C1, SPI3, GPIOB, RCC) и все битовые маски (I2C_CR1_START, SPI_SR_TXE и т.д.).
// ВАЖНО: в присланном тексте стояли кавычки-«ёлочки» (« »), скорее всего это артефакт
// распознавания фото. Компилятор принимает только "..." или <...>, поэтому здесь прямые кавычки.
#include "stm32f407xx.h"

// Объявляем внешнюю переменную-счётчик системного времени. Она определена в другом файле
// и, как правило, увеличивается на 1 каждую миллисекунду в обработчике SysTick_Handler.
// Замечание: переменную следует объявлять и определять как volatile, иначе при оптимизации
// компилятор может считать, что она не меняется, и цикл в delayMs зависнет навсегда.
extern uint32_t systemTimeCounter;

// Функция программной задержки в миллисекундах; delay - требуемая длительность в мс.
void delayMs(uint32_t delay)
{
   // Запоминаем значение счётчика в момент входа в функцию - это точка отсчёта задержки.
   uint32_t curr = systemTimeCounter;
   // Крутимся в пустом цикле, пока разность "текущее время - время старта" меньше delay.
   // Вычитание беззнаковых чисел корректно работает и при переполнении счётчика (через 2^32 мс).
   while (systemTimeCounter - curr < delay) { }
// Конец функции delayMs: управление возвращается вызывающему коду.
}

// Функция передачи массива байт по I2C1 в режиме мастера (запись в ведомое устройство).
// addr - адрес ведомого, data - указатель на передаваемые данные, count - число байт.
void I2C_SendData(uint8_t addr, uint8_t *data,
                 uint8_t count)
{
   // Индекс текущего передаваемого байта в массиве data, начинаем с нулевого.
   uint8_t i = 0;
   // Устанавливаем бит START в CR1: модуль I2C занимает шину и формирует условие START
   // (линия SDA падает при высокой SCL), одновременно переходя в режим мастера.
   I2C1->CR1 |= I2C_CR1_START;
   // Ждём, пока в SR1 не установится флаг SB (Start Bit) - он означает, что START отправлен.
   // Пока бит равен 0, цикл выполняется; тело цикла пустое, это просто опрос флага (polling).
   while ((I2C1->SR1 & I2C_SR1_SB) == 0U) { }
   /* Строки 38–47 не представлены на фотографиях.
      Здесь пропущена часть исходной функции. */
   // Пропущенный фрагмент (предположительно, исходя из последовательности работы I2C-мастера):
   // 1) запись в I2C1->DR адреса ведомого со сдвигом влево на 1 бит и битом R/W = 0 (запись),
   //    например (addr << 1); эта запись заодно сбрасывает флаг SB;
   // 2) ожидание флага ADDR в SR1 (адрес подтверждён ведомым ACK-ом);
   // 3) чтение SR1, затем SR2 - так сбрасывается флаг ADDR;
   // 4) заголовок цикла передачи, например while (i < count) {, который закрывается
   //    строкой "Конец цикла в исходнике" ниже.
   /* Видимый фрагмент из тела цикла передачи: */
   // Кладём очередной байт в регистр данных DR; аппаратура I2C сама сдвинет его на линию SDA.
   I2C1->DR = data[i];
   // Ждём флаг TXE (Transmit data register Empty): байт из DR переписан в сдвиговый регистр,
   // и DR свободен для следующего байта.
   while ((I2C1->SR1 & I2C_SR1_TXE) == 0U) { }
   // Ждём флаг BTF (Byte Transfer Finished): байт полностью передан и принят ACK,
   // сдвиговый регистр тоже пуст. Это гарантирует, что передача завершена до следующего шага.
   while ((I2C1->SR1 & I2C_SR1_BTF) == 0U) { }
   // Переходим к следующему байту массива.
   i++;
   /* Конец цикла в исходнике. */
   // Устанавливаем бит STOP в CR1: после текущего байта модуль формирует условие STOP
   // (SDA растёт при высокой SCL), шина освобождается, мастер переходит в режим ожидания.
   I2C1->CR1 |= I2C_CR1_STOP;
// Конец функции I2C_SendData.
// Замечание: в коде нет тайм-аутов и проверки флага AF (NACK), поэтому при отсутствии
// ведомого на шине любой из циклов ожидания может зависнуть навсегда.
}

// Функция обмена по SPI3 в режиме мастера: сначала отправляем n байт (команда/адрес/данные),
// затем читаем m байт ответа. Всё это одним сеансом при активном сигнале выбора (CS).
// tData - буфер передачи, n - его длина; rData - буфер приёма, m - число принимаемых байт.
void SPI_Trans(uint8_t *tData, uint8_t n,
              uint8_t *rData, uint8_t m)
{
   // Переменная для "выбрасываемых" байт, принятых во время передачи (их значение не нужно).
   uint8_t dummy;
   // Счётчик принятых байт на этапе чтения.
   uint8_t i;
   // Счётчик переданных байт на этапе передачи.
   uint8_t t;
   // Сбрасываем бит 2 в ODR порта B: линия PB2 уходит в низкий уровень.
   // PB2 выступает как программный CS (Chip Select, активный уровень - низкий): начало сеанса.
   GPIOB->ODR &= ~GPIO_ODR_ODR_2;
   // Начальное значение dummy (чтобы переменная не была неинициализированной).
   dummy = 0;
   // Начинаем с нулевого передаваемого байта.
   t = 0;
   // Цикл передачи: выполняем, пока не отправлены все n байт.
   while (t < n) {
       // Ждём флаг TXE в SR SPI3: буфер передачи пуст, можно записывать новый байт.
       while ((SPI3->SR & SPI_SR_TXE) == 0U) { }
       // Записываем байт в DR - SPI начинает его выдавать на MOSI, генерируя тактовые импульсы SCK.
       SPI3->DR = tData[t];
       // Ждём флаг RXNE: SPI - дуплексный интерфейс, и одновременно с каждым отправленным байтом
       // по MISO принимается байт; RXNE=1 означает, что он принят и лежит в DR.
       while ((SPI3->SR & SPI_SR_RXNE) == 0U) { }
       // Читаем DR: это сбрасывает RXNE и предотвращает ошибку переполнения (OVR) при следующем обмене.
       // Принятое значение во время передачи команды ничего не значит, поэтому оно отбрасывается.
       dummy = (uint8_t)SPI3->DR;
       // Переходим к следующему передаваемому байту.
       t++;
   // Конец цикла передачи.
   }
   // Обнуляем счётчик принятых байт перед этапом чтения.
   i = 0;
   // Цикл чтения: принимаем ровно m байт (если m = 0, цикл не выполняется).
   while (i < m) {
       // Ждём, пока буфер передачи освободится.
       while ((SPI3->SR & SPI_SR_TXE) == 0U) { }
       // Чтобы получить байт от ведомого, мастер обязан генерировать такты SCK, а они идут
       // только при передаче. Поэтому отправляем фиктивный байт 0xFF (его ведомый игнорирует).
       SPI3->DR = 0xFF;
       // Ждём, пока байт от ведомого будет принят.
       while ((SPI3->SR & SPI_SR_RXNE) == 0U) { }
       // Забираем принятый байт из DR и сохраняем в i-й элемент приёмного буфера.
       rData[i] = (uint8_t)SPI3->DR;
       // Переходим к следующей ячейке приёмного буфера.
       i++;
   // Конец цикла чтения.
   }
   // Ждём сброса флага BSY: обмен на шине SPI полностью завершён, последний такт SCK отработан.
   // Без этого CS мог бы подняться раньше окончания последнего бита.
   while ((SPI3->SR & SPI_SR_BSY) != 0U) { }
   // Устанавливаем бит 2 в ODR порта B: PB2 уходит в высокий уровень, CS снят, сеанс завершён.
   GPIOB->ODR |= GPIO_ODR_ODR_2;
// Конец функции SPI_Trans.
}

// Главная функция программы - точка входа после startup-кода.
int main(void)
{
   /* Начальная часть main, строки 86–104,
      не представлена на фотографиях. */
   // Пропущенный фрагмент (предположительно): включение тактирования GPIOB
   // (RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN), настройка SysTick на 1 мс для systemTimeCounter,
   // настройка PB2 как выхода push-pull и установка его в 1 (CS неактивен).
   // Без включения тактирования GPIOB дальнейшая настройка портов не будет работать.
   // SPI3 INIT
   // Комментарий автора: начало блока инициализации SPI3.
   // Включаем тактирование SPI3: он сидит на шине APB1, бит SPI3EN в регистре RCC->APB1ENR.
   // Пока тактирование выключено, запись в регистры SPI3 не имеет эффекта.
   RCC->APB1ENR |= RCC_APB1ENR_SPI3EN;
   /* Настройки GPIOB->MODER, OSPEEDR и AFR[0]
      частично обрезаны правой границей кадра.
      Видны AF6 и режим альтернативной функции. */
   // Пропущенный фрагмент (предположительно): ноги PB3 (SCK), PB4 (MISO), PB5 (MOSI) переводятся
   // в режим альтернативной функции (MODER = 10), задаётся высокая скорость (OSPEEDR)
   // и выбирается AF6 = SPI3 в регистре AFR[0] (AF6 - как раз то, что видно на фото).
   // Сбрасываем (&= ~) три группы бит в CR1 SPI3:
   // BR (делитель скорости) = 000 -> частота SCK = fPCLK1 / 2;
   // DFF = 0 -> размер кадра 8 бит; LSBFIRST = 0 -> старший бит передаётся первым (MSB first).
   SPI3->CR1 &= ~(SPI_CR1_BR | SPI_CR1_DFF |
                  SPI_CR1_LSBFIRST);
   // CPOL и CPHA не трогаем: после сброса они равны 0, то есть SPI mode 0
   // (SCK в покое низкий, данные считываются по переднему фронту).
   // SSM = 1 включает программное управление NSS, SSI = 1 задаёт его внутренний уровень "1".
   // Это нужно, чтобы мастер не уходил в ошибку MODF из-за "низкого" уровня на вывод NSS;
   // реальный CS формируется вручную на PB2.
   SPI3->CR1 |= SPI_CR1_SSI | SPI_CR1_SSM;
   // MSTR = 1: SPI3 работает как мастер (сам генерирует SCK).
   SPI3->CR1 |= SPI_CR1_MSTR;
   // SPE = 1: включаем периферийный модуль SPI3. Включение выполняется последним,
   // когда остальные параметры в CR1 уже заданы.
   SPI3->CR1 |= SPI_CR1_SPE;
   // I2C INIT
   // Комментарий автора: начало блока инициализации I2C1.
   // Включаем тактирование I2C1 (шина APB1, бит I2C1EN).
   RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;
   // Очищаем по 2 бита режима для PB6 и PB7 (на каждый вывод приходится по 2 бита в MODER).
   // Маска 3 (0b11), сдвинутая на позицию вывода, обнуляет оба бита.
   GPIOB->MODER &= ~((3 << GPIO_MODER_MODE6_Pos) |
                      (3 << GPIO_MODER_MODE7_Pos));
   // Записываем значение 2 (0b10) - режим альтернативной функции (Alternate Function)
   // для PB6 (SCL) и PB7 (SDA): ими теперь управляет периферия I2C1, а не регистр ODR.
   GPIOB->MODER |= (2 << GPIO_MODER_MODE6_Pos) |
                     (2 << GPIO_MODER_MODE7_Pos);
   // Выбираем тип выхода "открытый сток" (open-drain) для PB6 и PB7. Шина I2C требует именно его:
   // устройства только прижимают линию к земле, а высокий уровень создаётся подтягивающим резистором.
   // Замечание: подтяжки (PUPDR) здесь не включены, значит нужны внешние резисторы
   // (обычно 4.7 кОм) к питанию на линиях SCL и SDA.
   GPIOB->OTYPER |= GPIO_OTYPER_OT6 | GPIO_OTYPER_OT7;
   // Устанавливаем оба бита скорости (0b11) для PB6 и PB7: максимальная скорость переключения.
   GPIOB->OSPEEDR |= GPIO_OSPEEDER_OSPEEDR6 |
                      GPIO_OSPEEDER_OSPEEDR7;
   // В регистре AFR[0] (выводы 0..7) для PB6 и PB7 записываем номер альтернативной функции 4
   // (AF4 = I2C1 по таблице Alternate Function datasheet). Оператор |= допустим, т.к. после сброса там нули.
   GPIOB->AFR[0] |= (4 << GPIO_AFRL_AFSEL6_Pos) |
                     (4 << GPIO_AFRL_AFSEL7_Pos);
   // Включаем программный сброс I2C1 (SWRST): периферия приводится в начальное состояние,
   // это снимает возможное "залипание" шины после включения питания.
   I2C1->CR1 |= I2C_CR1_SWRST;
   // Выдерживаем паузу 10 мс, пока сброс действует (требуется работающий счётчик SysTick).
   delayMs(10);
   // Снимаем бит SWRST: сброс завершён, регистры готовы к настройке.
   I2C1->CR1 &= ~I2C_CR1_SWRST;
   // Записываем в поле FREQ регистра CR2 частоту тактирования APB1 в МГц - здесь 16 МГц
   // (значение соответствует внутреннему генератору HSI 16 МГц, если PLL не настраивался).
   // Это значение используется для расчёта временных интервалов I2C.
   I2C1->CR2 |= 16 << I2C_CR2_FREQ_Pos;
   // Регистр CCR задаёт скорость SCL. Значение 0x50 = 80, режим Standard (бит F/S = 0).
   // Период SCL = 2 * CCR * T(PCLK1) = 2 * 80 / 16 МГц = 10 мкс, то есть частота 100 кГц.
   I2C1->CCR |= 0x50;
   // TRISE - максимальное время нарастания фронта в тактах PCLK1 плюс 1.
   // Для Standard-режима 1000 нс: 1000 нс / 62.5 нс = 16, плюс 1 = 17 = 0x11.
   I2C1->TRISE |= 0x11;
   // Включаем периферию I2C1 (PE = 1). Выполняется после настройки CR2, CCR и TRISE,
   // потому что менять эти регистры при PE = 1 нельзя.
   I2C1->CR1 |= I2C_CR1_PE;
   // Массив из двух байт: 24 и 64 - тестовое сообщение для устройства на шине I2C
   // (смысл зависит от ведомого, например, команда или данные для индикатора).
   uint8_t test[2] = {24, 64};
   // Отправляем два байта тестового сообщения ведомому с адресом 0x10 (это значение
   // передаётся в параметр addr; как именно оно используется - в скрытой части функции).
   I2C_SendData(0x10, test, 2);
   // Буфер для передаваемых по SPI байт: [0] - команда/адрес регистра, [1] - значение для записи.
   uint8_t data[2];
   // Буфер для принятых по SPI данных: 12 байт (по 2 байта на 6 осей).
   uint8_t rData[12];
   // Адрес регистра 0x7E с установленным старшим битом (1 << 7): в SPI-датчиках этого типа
   // бит 7 = 1 означает чтение, бит 7 = 0 - запись. Итоговое значение 0xFE.
   data[0] = 0x7E | (1 << 7);
   // Читаем 1 байт из регистра 0x7E: отправляем 1 байт (адрес), принимаем 1 байт в rData.
   // Это "холостое" чтение: оно нужно, чтобы по фронту CS датчик переключил интерфейс в режим SPI.
   // (В типичном рецепте для BMI160 делают чтение регистра 0x7F; здесь использован 0x7E.)
   SPI_Trans(data, 1, rData, 1);
   // Адрес 0x7E без бита чтения = запись в регистр команд (CMD).
   data[0] = 0x7E; data[1] = 0x11;
   // Записываем команду 0x11 - перевод акселерометра в нормальный режим (Normal mode).
   // Передаём 2 байта (адрес + значение), приём не нужен: rData = 0 (нулевой указатель), m = 0.
   SPI_Trans(data, 2, 0, 0);
   // Ждём 5 мс - время запуска акселерометра (по документации порядка 4 мс).
   delayMs(5);
   // Снова запись в регистр команд 0x7E.
   data[0] = 0x7E; data[1] = 0x15;
   // Записываем команду 0x15 - перевод гироскопа в нормальный режим.
   SPI_Trans(data, 2, 0, 0);
   // Ждём 80 мс - время запуска гироскопа (около 55 мс, взят запас).
   delayMs(80);
   // Формируем адрес чтения: регистр 0x0C с битом чтения (1 << 7), итого 0x8C.
   // С регистра 0x0C начинаются данные: гироскоп X, Y, Z, затем акселерометр X, Y, Z,
   // по 2 байта на ось (сначала младший, затем старший), всего 12 байт.
   data[0] = 0x0C | (1 << 7);
   // Первое считывание: отправляем адрес (1 байт), затем принимаем 12 байт подряд.
   // CS удерживается в низком уровне всё время, датчик автоматически увеличивает адрес
   // (burst-чтение), поэтому одним сеансом читаются все 12 регистров.
   SPI_Trans(data, 1, rData, 12);
   // Бесконечный основной цикл программы (в МК без ОС выход из main недопустим).
   while (1) {
       // Пауза 1000 мс: данные опрашиваются и передаются раз в секунду.
       delayMs(1000);
       // Снова читаем 12 байт с регистра 0x0C; data[0] по-прежнему равно 0x8C.
       SPI_Trans(data, 1, rData, 12);
       // Цикл по буферу с шагом 2 байта: i = 0, 2, 4, 6, 8, 10 - то есть 6 итераций
       // (по одной на каждую ось: Gx, Gy, Gz, Ax, Ay, Az).
       for (int i = 0; i < 12; i += 2) {
           // Отправляем по I2C ведомому 0x10 пару байт (младший и старший байт значения оси).
           // rData + i - указатель на i-й элемент массива (арифметика указателей).
           I2C_SendData(0x10, rData + i, 2);
       // Конец цикла for.
       }
   // Конец бесконечного цикла while (1).
   }
// Конец функции main (до этой строки управление не доходит).
}