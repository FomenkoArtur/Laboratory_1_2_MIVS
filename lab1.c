#include <stdint.h>
// Подключаем стандартный заголовок с целочисленными типами фиксированной ширины:
// uint8_t, uint32_t и т.п. Нужен для описания переменных и параметров функций.

#include "stm32f407xx.h"
// Подключаем заголовок конкретного МК STM32F407xx. В нём определены адреса
// периферийных регистров (I2C2, SPI3, GPIOB, RCC), битовые маски
// (I2C_CR1_START, SPI_SR_TXE, GPIO_ODR_ODR_2 и др.) и типы регистров.

extern uint32_t systemTimeCounter;
// Объявляем внешнюю глобальную переменную systemTimeCounter. Она определена
// в другом модуле и, судя по использованию, увеличивается в обработчике
// системного таймера/SysTick. Используется как счётчик времени для задержек.

void delayMs(uint32_t delay)
// Функция блокирующей задержки. Параметр delay — желаемая задержка в
// условных «тиках» systemTimeCounter; если счётчик увеличивается раз в 1 мс,
// то это миллисекунды.

{
// Открывающая фигурная скобка тела функции delayMs.

   uint32_t curr = systemTimeCounter;
   // Запоминаем текущее значение счётчика времени на момент входа в функцию.
   // Это начальная точка отсчёта задержки.

   while (systemTimeCounter - curr < delay) { }
   // Ждём, пока разность между текущим значением счётчика и сохранённым curr
   // не станет больше или равна delay. Вычитание беззнаковое, поэтому код
   // корректно переживает переполнение счётчика. Цикл пустой — это busy-wait,
   // процессор всё время занят ожиданием.
}

void I2C_SendData(uint8_t addr, uint8_t *data,
                  uint8_t count)
// Функция предназначена для передачи count байт из массива data по шине I2C2
// устройству с адресом addr. Важно: в видимом фрагменте addr и count
// напрямую не используются, потому что часть тела функции пропущена.

{
// Начало тела функции I2C_SendData.

   uint8_t i = 0;
   // Индекс текущего передаваемого байта в массиве data. Начинаем с нуля.

   I2C2->CR1 |= I2C_CR1_START;
   // Устанавливаем бит START в регистре управления I2C2. Это команда
   // сформировать условие START на шине I2C (начало транзакции).

   while ((I2C2->SR1 & I2C_SR1_SB) == 0U) { }
   // Ожидаем установки флага SB (Start Bit) в регистре состояния SR1.
   // Флаг SB означает, что условие START действительно сгенерировано.
   // Пока флаг не установлен, процессор крутится в пустом цикле.

   /* Строки 38–47 не представлены на фотографиях.
      Здесь пропущена часть исходной функции. */
   // В этих пропущенных строках, вероятно, находится:
   // - ожидание флага ADDR и очистка ADDR;
   // - запись адреса addr (обычно addr << 1) в I2C2->DR;
   // - заголовок цикла по count;
   // - обработка ошибок/ожидание готовности.
   // Точный код восстановить по видимому фрагменту нельзя.

   /* Видимый фрагмент из тела цикла передачи: */
   // Ниже идёт тело цикла передачи байтов. Сам заголовок цикла
   // (например, while (i < count)) находится в пропущенной части.

   I2C2->DR = data[i];
   // Записываем очередной байт data[i] в регистр данных I2C2->DR.
   // После записи периферия I2C начинает выдвигать этот байт на шину.

   while ((I2C2->SR1 & I2C_SR1_TXE) == 0U) { }
   // Ожидаем флаг TXE (Transmit Data Register Empty). Он означает,
   // что регистр данных освободился и в него можно записать следующий байт.
   // Пока TXE не установлен, ждём.

   while ((I2C2->SR1 & I2C_SR1_BTF) == 0U) { }
   // Ожидаем флаг BTF (Byte Transfer Finished). Он означает, что
   // передача байта завершена и регистр данных пуст. Для простой передачи
   // этот цикл гарантирует, что байт реально ушёл, прежде чем двигаться дальше.

   i++;
   // Увеличиваем индекс, чтобы при следующей итерации цикла взять
   // следующий байт из массива data.

   /* Конец цикла в исходнике. */
   // Здесь заканчивается тело цикла. Закрывающая скобка и условие цикла
   // находятся в пропущенной части исходника.

   I2C2->CR1 |= I2C_CR1_STOP;
   // Устанавливаем бит STOP в CR1. Это команда сформировать условие STOP
   // на шине I2C, то есть завершить транзакцию.

   // Важное замечание: в видимом фрагменте count и addr не используются.
   // Если цикл в пропущенной части есть, count используется там; addr,
   // скорее всего, используется при передаче адреса. Также видимый код
   // не проверяет ошибки I2C (AF, BERR, ARLO и т.п.).
}

void SPI_Trans(uint8_t *tData, uint8_t n,
               uint8_t *rData, uint8_t m)
// Функция обмена по SPI3. Сначала передаёт n байт из массива tData,
// затем, если m > 0, принимает m байт в массив rData. Для приёма
// приходится передавать фиктивные байты 0xFF, чтобы тактировать шину.
// Перед обменом опускает CS на PB2, после обмена поднимает его обратно.

{
// Начало тела функции SPI_Trans.

   uint8_t dummy;
   // Временная переменная для чтения регистра данных SPI при передаче.
   // При full-duplex SPI каждый переданный байт одновременно принимается;
   // чтобы очистить RXNE и не потерять данные, принятый байт куда-то читают.

   uint8_t i;
   // Индекс для цикла приёма m байт.

   uint8_t t;
   // Индекс для цикла передачи n байт.

   GPIOB->ODR &= ~GPIO_ODR_ODR_2;
   // Сбрасываем бит 2 в регистре выходных данных GPIOB. Это переводит
   // линию PB2 в низкий уровень. Судя по логике, PB2 используется как
   // аппаратный CS (chip select) для SPI-устройства, активный низким уровнем.
   // Предполагается, что PB2 ранее настроен как выход.

   dummy = 0;
   // Инициализируем dummy нулём, чтобы избежать предупреждения о
   // неинициализированной переменной. Значение далее будет перезаписано.

   t = 0;
   // Начинаем передачу с первого байта массива tData.

   while (t < n) {
   // Цикл передачи n байт из tData.

       while ((SPI3->SR & SPI_SR_TXE) == 0U) { }
       // Ожидаем установки флага TXE (Transmit buffer Empty) в регистре
       // состояния SPI3. Флаг означает, что буфер передачи пуст и в DR
       // можно записать следующий байт.

       SPI3->DR = tData[t];
       // Записываем очередной байт tData[t] в регистр данных SPI3.
       // Это запускает передачу байта по SPI. Так как SPI настроен
       // как 8-битный (DFF=0), записывается один байт.

       while ((SPI3->SR & SPI_SR_RXNE) == 0U) { }
       // Ожидаем флага RXNE (Receive buffer Not Empty). При передаче
       // SPI одновременно принимает байт; нужно дождаться, пока приёмный
       // буфер заполнится, иначе можно потерять/заблокировать обмен.

       dummy = (uint8_t)SPI3->DR;
       // Читаем принятый байт из DR. При передаче он нам не нужен,
       // поэтому сохраняем его в dummy. Чтение DR очищает флаг RXNE.

       t++;
       // Переходим к следующему передаваемому байту.
   }
   // Конец цикла передачи n байт.

   i = 0;
   // Начинаем приём с первого байта массива rData.

   while (i < m) {
   // Цикл приёма m байт в rData.

       while ((SPI3->SR & SPI_SR_TXE) == 0U) { }
       // Снова ждём, пока буфер передачи освободится, чтобы записать
       // фиктивный байт для тактирования приёма.

       SPI3->DR = 0xFF;
       // Записываем 0xFF в DR. Это фиктивный байт: он нужен только для
       // генерации тактовых импульсов, чтобы ведомое устройство выдало
       // очередной байт. Реальное значение 0xFF на MISO не влияет.

       while ((SPI3->SR & SPI_SR_RXNE) == 0U) { }
       // Ждём, пока в приёмном буфере появится байт от ведомого устройства.

       rData[i] = (uint8_t)SPI3->DR;
       // Читаем принятый байт и сохраняем его в rData[i]. Чтение DR
       // очищает RXNE. Если m > 0, rData должен указывать на корректный
       // буфер достаточного размера.

       i++;
       // Переходим к следующему принимаемому байту.
   }
   // Конец цикла приёма m байт.

   while ((SPI3->SR & SPI_SR_BSY) != 0U) { }
   // Ожидаем, пока флаг BSY (Busy) не сбросится. Это гарантирует,
   // что последний байт полностью передан и SPI-периферия не занята.
   // Только после этого можно поднимать CS.

   GPIOB->ODR |= GPIO_ODR_ODR_2;
   // Устанавливаем PB2 в высокий уровень. Это деактивирует CS
   // (предполагается активный низкий уровень) и завершает обмен
   // с SPI-устройством.
}

int main(void)
// Главная функция программы. Выполняется после старта МК и инициализации
// системы. В видимом фрагменте нет начала main, поэтому часть начальной
// инициализации (например, тактирование GPIOB, настройка PB2 как выхода,
// настройка пинов SPI3) пропущена.

{
// Начало тела main.

   /* Начальная часть main, строки 86–104,
      не представлена на фотографиях. */
   // В пропущенной части, вероятно, находятся:
   // - включение тактирования GPIOB и других портов;
   // - настройка PB2 как выхода для CS;
   // - настройка выводов SPI3 (SCK/MISO/MOSI) в альтернативную функцию AF6;
   // - возможно, настройка SysTick для systemTimeCounter;
   // - другие инициализации.
   // Комментировать эти строки нельзя, так как их нет в файле.

   // SPI3 INIT
   // Комментарий-разделитель: далее идёт инициализация SPI3.

   RCC->APB1ENR |= RCC_APB1ENR_SPI3EN;
   // Включаем тактирование периферии SPI3. SPI3 висит на шине APB1,
   // поэтому устанавливаем соответствующий бит в регистре APB1ENR.
   // Без тактирования регистры SPI3 недоступны.

   /* Настройки GPIOB->MODER, OSPEEDR и AFR[0]
      частично обрезаны правой границей кадра.
      Видны AF6 и режим альтернативной функции. */
   // Здесь в исходнике настраиваются GPIO для SPI3. По видимым признакам
   // используется альтернативная функция AF6. Для STM32F407 SPI3 обычно
   // выводится на PB3 (SCK), PB4 (MISO), PB5 (MOSI) с AF6. Точные строки
   // настройки MODER/OSPEEDR/AFR обрезаны, поэтому построчно не комментируются.

   SPI3->CR1 &= ~(SPI_CR1_BR | SPI_CR1_DFF |
                  SPI_CR1_LSBFIRST);
   // В регистре управления SPI3 CR1 очищаем:
   // - BR: биты делителя тактовой частоты SPI;
   // - DFF: формат кадра данных (сбрасываем в 0 => 8-битный кадр);
   // - LSBFIRST: порядок битов (сбрасываем => сначала старший бит, MSB first).
   // Остальные биты CR1 не трогаем.

   SPI3->CR1 |= SPI_CR1_SSI | SPI_CR1_SSM;
   // Устанавливаем SSM (Software Slave Management) и SSI.
   // SSM=1 означает, что сигнал NSS управляется программно, а не внешним
   // пином. SSI=1 задаёт внутренний высокий уровень NSS. Это типичная
   // настройка для ведущего SPI, чтобы избежать ошибки mode fault, когда
   // NSS не используется аппаратно.

   SPI3->CR1 |= SPI_CR1_MSTR;
   // Устанавливаем бит MSTR: SPI3 работает в режиме ведущего (Master).
   // Именно мастер генерирует тактовый сигнал SCK.

   SPI3->CR1 |= SPI_CR1_SPE;
   // Устанавливаем бит SPE (SPI Enable): включаем периферию SPI3.
   // После этого SPI3 готов к обмену.

   // I2C2 INIT
   // Комментарий-разделитель: далее идёт инициализация I2C2.

   RCC->APB1ENR |= RCC_APB1ENR_I2C2EN;
   // Включаем тактирование I2C2 на шине APB1. Без этого регистры I2C2
   // не будут работать.

   GPIOB->MODER &= ~((3 << GPIO_MODER_MODE10_Pos) |
                     (3 << GPIO_MODER_MODE11_Pos));
   // Очищаем по два бита MODER для выводов PB10 и PB11.
   // Каждый вывод имеет 2 бита режима; маска 3 (двоичное 11) сдвинутая
   // на позицию нужного вывода очищает оба бита. Сначала сбрасываем
   // текущий режим, чтобы затем явно записать новый.

   GPIOB->MODER |= (2 << GPIO_MODER_MODE10_Pos) |
                    (2 << GPIO_MODER_MODE11_Pos);
   // Устанавливаем для PB10 и PB11 режим 10 (двоичное 2) —
   // альтернативная функция (Alternate Function). Именно в этом режиме
   // выводы управляются периферией I2C2.

   GPIOB->OTYPER |= GPIO_OTYPER_OT10 | GPIO_OTYPER_OT11;
   // Устанавливаем биты OTYPER для PB10 и PB11 в 1. Для GPIO это означает
   // открытый сток (open-drain). Шина I2C требует открытого стока:
   // вывод может только притягивать линию к земле, а подтяжка к питанию
   // осуществляется внешними резисторами.

   GPIOB->OSPEEDR |= GPIO_OSPEEDER_OSPEEDR10 |
                     GPIO_OSPEEDER_OSPEEDR11;
   // Настраиваем скорость переключения выводов PB10 и PB11.
   // Установка соответствующих битов OSPEEDR задаёт высокую скорость
   // (в зависимости от макросов — обычно максимальную/высокую).
   // Для I2C это не критично, но типично для быстрых фронтов.

   GPIOB->AFR[1] |= (4 << GPIO_AFRH_AFSEL10_Pos) |
                    (4 << GPIO_AFRH_AFSEL11_Pos);
   // AFR[1] — регистр альтернативных функций для выводов 8..15.
   // Записываем значение 4 в поля AFSEL10 и AFSEL11. AF4 для PB10/PB11
   // на STM32F407 соответствует I2C2 (PB10 — I2C2_SCL, PB11 — I2C2_SDA).

   I2C2->CR1 |= I2C_CR1_SWRST;
   // Устанавливаем бит SWRST в CR1 — программный сброс периферии I2C2.
   // Это приводит регистры I2C2 к начальному состоянию.

   delayMs(10);
   // Ждём примерно 10 мс, чтобы сброс I2C2 гарантированно завершился.
   // Задержка реализована через systemTimeCounter.

   I2C2->CR1 &= ~I2C_CR1_SWRST;
   // Снимаем бит SWRST: выводим I2C2 из состояния сброса.
   // После этого можно настраивать регистры I2C2.

   I2C2->CR2 |= 16 << I2C_CR2_FREQ_Pos;
   // Записываем в поле FREQ регистра CR2 значение 16.
   // Это сообщает периферии I2C2, что частота тактирования APB1 равна
   // 16 МГц. Значение используется для расчёта таймингов I2C.
   // Важно: здесь используется |=, а не очистка поля; после SWRST поле
   // должно быть нулевым, поэтому результат корректен.

   I2C2->CCR |= 0x50;
   // Настраиваем регистр CCR (Clock Control Register). 0x50 = 80.
   // Для стандартного режима I2C при частоте APB1 16 МГц значение CCR=80
   // обычно даёт SCL около 100 кГц. Бит FS (Fast Mode) здесь не установлен,
   // то есть выбран стандартный режим.

   I2C2->TRISE |= 0x11;
   // Задаём максимальное время нарастания сигнала на шине I2C.
   // 0x11 = 17. Для стандартного режима при 16 МГц TRISE рассчитывается
   // как (1000 нс / период APB1) + 1 = 16 + 1 = 17. Это соответствует
   // требованиям I2C для стандартного режима.

   I2C2->CR1 |= I2C_CR1_PE;
   // Устанавливаем бит PE (Peripheral Enable): включаем I2C2.
   // После этого периферия I2C2 активна и может работать на шине.

   uint8_t test[2] = {24, 64};
   // Создаём тестовый массив из двух байт: 24 (0x18) и 64 (0x40).
   // Предположительно это данные для проверки записи по I2C.

   I2C_SendData(0x10, test, 2);
   // Вызываем функцию передачи по I2C2: адрес 0x10, данные test,
   // количество 2 байта. Важно: в видимом фрагменте I2C_SendData
   // параметры addr и count не используются из-за пропущенных строк,
   // поэтому реальное поведение зависит от отсутствующего кода.

   uint8_t data[2];
   // Буфер для SPI-команд. Размер 2 байта достаточно для команд,
   // которые далее отправляются: один или два байта.

   uint8_t rData[12];
   // Буфер для приёма 12 байт по SPI. Далее в него читаются ответы
   // SPI-устройства.

   data[0] = 0x7E | (1 << 7);
   // Формируем первый байт команды: 0x7E с установленным старшим битом.
   // 0x7E = 0111 1110, после OR с 0x80 получаем 0xFE.
   // Обычно старший бит означает «чтение» для многих SPI-датчиков.

   SPI_Trans(data, 1, rData, 1);
   // Отправляем 1 байт (data[0] = 0xFE) и принимаем 1 байт в rData.
   // Это, вероятно, чтение одного регистра/идентификатора по SPI.

   data[0] = 0x7E; data[1] = 0x11;
   // Формируем двухбайтовую команду: 0x7E, 0x11.
   // Вторая строка в одной физической строке — две операции присваивания.

   SPI_Trans(data, 2, 0, 0);
   // Отправляем 2 байта, приём не нужен: rData = 0, m = 0.
   // В функции SPI_Trans цикл приёма не выполнится, и rData не разыменовывается.

   delayMs(5);
   // Ждём 5 мс после команды. Задержка может быть нужна устройству
   // для обработки команды/записи.

   data[0] = 0x7E; data[1] = 0x15;
   // Формируем следующую двухбайтовую команду: 0x7E, 0x15.
   // Снова две операции присваивания в одной строке.

   SPI_Trans(data, 2, 0, 0);
   // Отправляем 2 байта команды, ничего не принимаем.

   delayMs(80);
   // Ждём 80 мс. Для некоторых датчиков после команды 0x15 требуется
   // более длительная задержка, например для запуска измерения/преобразования.

   data[0] = 0x0C | (1 << 7);
   // Формируем байт 0x0C с установленным старшим битом: 0x8C.
   // Вероятно, это команда чтения 12 байт из устройства.

   SPI_Trans(data, 1, rData, 12);
   // Отправляем 1 байт команды (0x8C) и принимаем 12 байт в rData.
   // Внутри SPI_Trans после отправки команды будет отправлено 12 байт 0xFF
   // для тактирования приёма.

   while (1) {
   // Бесконечный цикл главной программы. После инициализации программа
   // постоянно повторяет чтение по SPI и передачу данных по I2C.

       delayMs(1000);
       // Ждём примерно 1000 мс (1 секунду), если systemTimeCounter
       // увеличивается с частотой 1 кГц. Это период опроса.

       SPI_Trans(data, 1, rData, 12);
       // Отправляем 1 байт из data (там осталось 0x8C — команда чтения)
       // и принимаем 12 байт в rData. То есть каждый цикл читаем 12 байт
       // с SPI-устройства.

       for (int i = 0; i < 12; i += 2) {
       // Цикл по принятому массиву rData с шагом 2. i принимает значения
       // 0, 2, 4, 6, 8, 10. То есть данные передаются парами байт.

           I2C_SendData(0x10, rData + i, 2);
           // Передаём по I2C2 два байта: rData[i] и rData[i+1].
           // Адрес устройства — 0x10. Указатель rData + i указывает на
           // начало очередной пары. В видимой реализации I2C_SendData
           // есть пропуски, поэтому фактическая передача зависит от
           // отсутствующего кода.
       }
       // Конец for-цикла передачи пар байт по I2C.

   }
   // Конец бесконечного while(1). Сюда управление никогда не выходит
   // штатно, если только не произойдёт сбой/сброс.
}
